"""Generate the PyPTO ``kernel_entry`` adapter for a cce-mlir device object.

PyPTO dispatches kernels through ``kernel_entry(__gm__ int64_t* args)``, where
each argument is a device ``Tensor`` descriptor; cce-mlir's device entry takes
one raw GM pointer per parameter. The adapter bridges the two: it unpacks each
descriptor to its GM data pointer and calls the cce-mlir entry.

No literal from the fixture appears here: symbols, parameter order, element
types and the device entry name all come from the typed kernel IR.
"""

from __future__ import annotations

from .kernel_ir import CceKernel

__all__ = ["generate_adapter_source"]


_HEADER = """\
// Generated by PyPTO's cce-mlir backend: kernel_entry adapter.
#include <cstdint>

#ifndef __gm__
#define __gm__
#endif

#ifndef __aicore__
#if defined(__CPU_SIM)
#define __aicore__
#else
#define __aicore__ [aicore]
#endif
#endif

#include "tensor.h"
"""


def _identifier(name: str) -> str:
    """Return a C-identifier-safe spelling of a parameter name."""
    sanitized = "".join(character if character.isalnum() or character == "_" else "_" for character in name)
    return sanitized if sanitized and not sanitized[0].isdigit() else f"_{sanitized}"


def generate_adapter_source(kernel: CceKernel) -> str:
    """Render the adapter C++ source for one kernel.

    Args:
        kernel: Typed kernel IR. Only tensor parameters are supported; the
            front end already refuses scalar parameters.

    Returns:
        C++ source defining ``kernel_entry`` and calling ``device_symbol``.
    """
    parameters = kernel.parameters
    declaration = ", ".join(f"__gm__ {parameter.element.c_type}*" for parameter in parameters)
    lines = [
        _HEADER,
        f'extern "C" __aicore__ void {kernel.device_symbol}({declaration});',
        "",
        'extern "C" __aicore__ void kernel_entry(__gm__ int64_t* args) {',
    ]
    call_arguments: list[str] = []
    for index, parameter in enumerate(parameters):
        name = _identifier(parameter.name)
        c_type = parameter.element.c_type
        lines.append(f"    // argument {index}: {parameter.space.value} {parameter.element.mlir}")
        lines.append(f"    __gm__ Tensor* {name}_tensor = reinterpret_cast<__gm__ Tensor*>(args[{index}]);")
        lines.append(
            f"    __gm__ {c_type}* {name} = reinterpret_cast<__gm__ {c_type}*>("
            f"static_cast<uintptr_t>({name}_tensor->buffer.addr)) + "
            f"{name}_tensor->start_offset;"
        )
        call_arguments.append(name)
    lines.append(f"    {kernel.device_symbol}({', '.join(call_arguments)});")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)
